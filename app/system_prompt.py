def sub_instruction(name):
    """Инструкция суб-агента (callable для ADK): своя роль + общие правила + резюме
    ТЕКУЩЕГО пользователя. Раньше суб-агенты не видели резюме («нет данных о вашем
    профиле»), а writer ссылался на «правило 8» из промпта координатора, которого
    в его собственном промпте не было."""
    def provider(ctx):
        parts = [SUB_INSTRUCTIONS[name], COMMON_RULES]
        if name == "writer_agent":
            parts.append(LETTER_RULES)
        parts.append(profile_summary(getattr(ctx, "user_id", "") or ""))
        return "\n".join(parts)
    return provider


def all_instructions():
    """Все тексты инструкций агентов (для пост-фильтра утечек — слой 3 guardrails).
    Сводка резюме сюда не входит: это данные самого пользователя, а не секрет —
    письмо, цитирующее опыт работы из резюме (8+ слов подряд), раньше ложно
    отклонялось как «утечка промпта»."""
    return "\n".join([BASE_PROMPT, ROUTER_NOTE, NO_PROFILE_NOTE, COMMON_RULES, LETTER_RULES] +
                     list(SUB_INSTRUCTIONS.values()))
