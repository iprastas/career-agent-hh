def all_instructions(profile_id="anastasia"):
    """Все тексты инструкций агентов (для пост-фильтра утечек — слой 3 guardrails)."""
    return "\n".join([BASE_PROMPT, ROUTER_NOTE, profile_summary(profile_id)] +
                    list(SUB_INSTRUCTIONS.values()))
