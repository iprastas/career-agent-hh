NO_PROFILE_NOTE = ("""Профиль пользователя ещё не заполнен (резюме отсутствует).
Предложи заполнить резюме во вкладке «Навыки»: прикрепить файл резюме (PDF/TXT)
или заполнить форму. Пока профиль пуст, инструменты match_profile, skill_gap и
fresh_vacancies вернут ошибку — не выдумывай их результаты, а поиск по ключевым
словам (search_vacancies и др.) работает без профиля.""")


def profile_summary(profile_id="anastasia"):
    """Короткая сводка профиля из data/profiles/<id>.json для инъекции в промпт.
    Профиль каждого пользователя свой (u<id>.json) — чужие резюме не подставляются."""
    p = os.path.join(config.PROFILES_DIR, (profile_id or "") + ".json")
    if not os.path.exists(p):
        return NO_PROFILE_NOTE
    d = json.load(open(p, encoding="utf-8"))
    core = [(s["name"] if isinstance(s, dict) else s) for s in d.get("skills", [])
            if not isinstance(s, dict) or s.get("weight") in ("core", "extra", None)]
    core = [s for s in core if s][:12]
    pref = d.get("preferences", {}) or {}
    lines = [
        "Профиль пользователя (для персонализации подбора):",
        "- должность: " + d.get("title", ""),
        "- город: " + d.get("location", ""),
        "- опыт: " + str(d.get("experience_years", "")) + " лет",
        "- ключевые навыки: " + ", ".join(core[:12]),
        "- ожидаемая зарплата: " + str(pref.get("salary_net", "")) + " ₽ на руки",
    ]
    return "\n".join(lines)


def build_instruction(profile_id="anastasia"):
    return BASE_PROMPT + "\n" + ROUTER_NOTE + "\n" + profile_summary(profile_id)


def dynamic_instruction(ctx):
    """Инструкция для ADK LlmAgent (callable): резюме подставляется из профиля
    ТЕКУЩЕГО пользователя (data/profiles/u<id>.json) — один пользователь никогда
    не видит данные другого. Если профиля нет — подсказка заполнить его."""
    uid = getattr(ctx, "user_id", "") or ""
    return build_instruction(uid)


