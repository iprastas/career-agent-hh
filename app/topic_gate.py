"""
Классификатор тем (guardrails, слой 1.5): семантическая проверка «в теме / не по теме».

Детерминированно и офлайн: TF-IDF (униграммы+биграммы) + центроиды двух классов
на размеченных образцах (карьера / не карьера). Работает ДО вызова модели: запрос,
семантически далёкий от карьерной темы, отклоняется без LLM. Regex-слой (guardrails)
ловит инъекции, этот слой — «просто не по теме» (стихи, погода, код, рецепты…).
Короткие служебные реплики («привет», «спасибо») пропускаются — по ним решает модель.
"""
