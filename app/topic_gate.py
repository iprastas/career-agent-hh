NEUTRAL_MAX_LEN = 18   # короче — служебная реплика, решает модель
THRESHOLD = 0.02       # score = cos(карьера) - cos(не-карьера); ниже — отказ без модели

_vectorizer = TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True)
_MATRIX = _vectorizer.fit_transform(CAREER_SEEDS + OFFTOPIC_SEEDS)
_n = len(CAREER_SEEDS)


def _centroid(rows):
    arr = np.asarray(rows.mean(axis=0))  # средний TF-IDF-вектор класса
    norm = float(np.sqrt((arr ** 2).sum()))
    return (arr / norm) if norm else arr


_C_CAREER = _centroid(_MATRIX[:_n])
_C_OFFTOPIC = _centroid(_MATRIX[_n:])


def classify(text):
    """-> (label, score): label 'career' | 'offtopic' | 'neutral', score = cos(карьера)-cos(не-карьера)."""
    t = re.sub(r"\s+", " ", (text or "").strip().lower())
    if not t:
        return "neutral", 0.0
    if len(t) <= NEUTRAL_MAX_LEN:
        return "neutral", 0.0
    v = _vectorizer.transform([t])
    c1 = float(cosine_similarity(v, _C_CAREER)[0][0])
    c2 = float(cosine_similarity(v, _C_OFFTOPIC)[0][0])
    score = c1 - c2
    return ("offtopic" if score < THRESHOLD else "career"), round(score, 4)


def is_offtopic(text):
    """True — запрос семантически не по теме (отклонять без вызова модели)."""
    return classify(text)[0] == "offtopic"
